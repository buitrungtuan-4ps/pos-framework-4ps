//! `cargo xtask gen-docs`: the documents generated from the tree into `docs/generated/`
//! ([ADR-0170](../../docs/adr/0170-repository-layout-code-naming-and-size-rules.md) decision 1).
//!
//! - `crate-graph.md`: the workspace crates by layer, as a Mermaid graph of the dependencies outside
//!   tests, and a table of each crate's dependents. From `cargo metadata` and each crate's contract
//!   card. It changes only when a dependency or a card does.
//! - `adr-index.md`: the ADRs nothing cites, and the citations of ADRs that do not exist. A
//!   citation is `ADR-NNNN`, or a link to `adr/NNNN-…`, in a tracked file under [`CITING_ROOTS`].
//!   It changes only when an ADR is first cited, stops being cited, or is added.
//!
//! Both are deterministic: everything is sorted and nothing records a time, so the same tree always
//! renders the same bytes. `--check` renders in memory and fails where a committed file differs,
//! the way the snapshots do; without it the files are written. Either way, **a citation of an ADR
//! that does not exist is a finding**: that list must stay empty.
//!
//! The full map of which file cites which ADR changes with almost every pull request, so it is not
//! committed. `--adr-citations [ADR-NNNN]` prints it, for every ADR or for one, as Markdown on
//! standard output.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::Path;

use crate::Finding;
use crate::checks::crates::{Crate, LAYERS, dependents, load};
use crate::checks::{Error, repo_root};

/// Where the generated documents live.
const OUT_DIR: &str = "docs/generated";

/// The tracked trees whose files are searched for ADR citations: all the code, and CI.
const CITING_ROOTS: [&str; 8] = [
    "crates",
    "countries",
    "examples",
    "apps",
    "ui",
    "dashboard",
    "xtask",
    ".github",
];

/// The line every generated file opens with after its title.
const GENERATED: &str =
    "<!-- Generated by `cargo xtask gen-docs`. Do not edit: run it and commit the result. -->";

/// What the arguments ask for.
enum Mode {
    /// Write the documents.
    Write,
    /// Compare the documents with what is committed.
    Check,
    /// Print the citation map, for every ADR or for one.
    Citations(Option<u32>),
}

/// The usage line, for an argument this does not understand.
const USAGE: &str = "usage: cargo xtask gen-docs [--check | --adr-citations [ADR-NNNN]]";

/// Writes the documents, checks them, or prints the citation map (see the module docs).
///
/// # Errors
///
/// [`Error`] if the tree, `git ls-files` or `cargo metadata` cannot be read, a file cannot be
/// written, or an argument is unknown.
pub fn run(args: &[String]) -> Result<Vec<Finding>, Error> {
    let mode = match args {
        [] => Mode::Write,
        [flag] if flag == "--check" => Mode::Check,
        [flag] if flag == "--adr-citations" => Mode::Citations(None),
        [flag, adr] if flag == "--adr-citations" => {
            let number = adr
                .strip_prefix("ADR-")
                .unwrap_or(adr)
                .parse()
                .map_err(|_| USAGE)?;
            Mode::Citations(Some(number))
        }
        _ => return Err(USAGE.into()),
    };
    let root = repo_root();
    let adrs = adr_titles(&root.join("docs/adr"))?;
    let citations = citations(&citing_files(&root)?);
    if let Mode::Citations(only) = mode {
        print!("{}", citation_map(&adrs, &citations, only));
        return Ok(Vec::new());
    }
    let crates = load(&root)?;
    let mut findings = dangling_findings(&adrs, &citations);
    for (path, text) in documents(&crates, &adrs, &citations) {
        if matches!(mode, Mode::Check) {
            if !matches_committed(&root, &path, &text) {
                findings.push(
                    Finding::new(&path, "gen-docs", "is not what the tree generates")
                        .with_hint("run `cargo xtask gen-docs` and commit the result"),
                );
            }
        } else {
            std::fs::create_dir_all(root.join(OUT_DIR))?;
            std::fs::write(root.join(&path), text)?;
        }
    }
    Ok(findings)
}

/// Each generated document's path and what the tree renders for it.
fn documents(
    crates: &[Crate],
    adrs: &BTreeMap<u32, (String, String)>,
    citations: &Citations,
) -> [(String, String); 2] {
    [
        (format!("{OUT_DIR}/crate-graph.md"), crate_graph(crates)),
        (
            format!("{OUT_DIR}/adr-index.md"),
            adr_index(adrs, citations),
        ),
    ]
}

/// True when the committed file at `path` is exactly `text`.
fn matches_committed(root: &Path, path: &str, text: &str) -> bool {
    std::fs::read_to_string(root.join(path)).ok().as_deref() == Some(text)
}

/// Each generated document's path, and whether the committed file is what the tree renders.
///
/// # Errors
///
/// [`Error`] if the tree, `git ls-files` or `docs/adr/` cannot be read.
pub fn up_to_date(crates: &[Crate]) -> Result<Vec<(String, bool)>, Error> {
    let root = repo_root();
    let adrs = adr_titles(&root.join("docs/adr"))?;
    let citations = citations(&citing_files(&root)?);
    Ok(documents(crates, &adrs, &citations)
        .into_iter()
        .map(|(path, text)| {
            let current = matches_committed(&root, &path, &text);
            (path, current)
        })
        .collect())
}

/// A Mermaid node id for a crate name.
fn node(name: &str) -> String {
    name.replace('-', "_")
}

/// One table cell, with any `|` escaped.
fn cell(text: &str) -> String {
    text.replace('|', "\\|")
}

/// `` `a`, `b` `` or an em dash.
fn names(set: &BTreeSet<String>) -> String {
    if set.is_empty() {
        return "—".to_owned();
    }
    set.iter()
        .map(|n| format!("`{n}`"))
        .collect::<Vec<_>>()
        .join(", ")
}

/// A crate's layer and purpose from its card, or empty strings.
fn card_field(krate: &Crate, field: &str) -> String {
    krate
        .card
        .as_ref()
        .and_then(|card| card[field].as_str())
        .unwrap_or_default()
        .to_owned()
}

/// Renders `crate-graph.md`.
#[must_use]
pub fn crate_graph(crates: &[Crate]) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "# Crate graph\n\n{GENERATED}\n");
    let _ = writeln!(
        out,
        "The workspace crates by layer, from `cargo metadata` and each crate's \
         `[package.metadata.pos]` card. An arrow points from a crate to a workspace crate it uses \
         outside tests. Dependencies only tests use are in the table.\n"
    );
    let _ = writeln!(out, "```mermaid\nflowchart LR");
    for layer in LAYERS {
        let members: Vec<&Crate> = crates
            .iter()
            .filter(|k| card_field(k, "layer") == layer)
            .collect();
        if members.is_empty() {
            continue;
        }
        let _ = writeln!(out, "  subgraph {layer}");
        for krate in members {
            let _ = writeln!(out, "    {}[\"{}\"]", node(&krate.name), krate.name);
        }
        let _ = writeln!(out, "  end");
    }
    let mut sorted: Vec<&Crate> = crates.iter().collect();
    sorted.sort_by(|a, b| a.name.cmp(&b.name));
    for krate in &sorted {
        for dependency in &krate.normal {
            let _ = writeln!(out, "  {} --> {}", node(&krate.name), node(dependency));
        }
    }
    let _ = writeln!(out, "```\n");
    let _ = writeln!(
        out,
        "| Crate | Layer | Path | Purpose | Used by | Used in tests by |"
    );
    let _ = writeln!(out, "|---|---|---|---|---|---|");
    for krate in &sorted {
        let (used, tested) = dependents(crates, &krate.name);
        let _ = writeln!(
            out,
            "| `{}` | {} | `{}` | {} | {} | {} |",
            krate.name,
            card_field(krate, "layer"),
            krate.dir,
            cell(&card_field(krate, "purpose")),
            names(&used),
            names(&tested)
        );
    }
    out
}

/// Each ADR's number, file name and title, from `docs/adr/NNNN-*.md`.
fn adr_titles(dir: &Path) -> Result<BTreeMap<u32, (String, String)>, Error> {
    let mut adrs = BTreeMap::new();
    for entry in std::fs::read_dir(dir)? {
        let file = entry?.file_name().to_string_lossy().into_owned();
        let Some(number) = file.get(..4).and_then(|digits| digits.parse::<u32>().ok()) else {
            continue;
        };
        let text = std::fs::read_to_string(dir.join(&file))?;
        let heading = text
            .lines()
            .next()
            .unwrap_or_default()
            .trim_start_matches('#')
            .trim();
        let title = heading
            .split_once(" — ")
            .filter(|(label, _)| label.starts_with("ADR-"))
            .map_or(heading, |(_, title)| title);
        adrs.insert(number, (file, title.to_owned()));
    }
    Ok(adrs)
}

/// The tracked files under [`CITING_ROOTS`] that are text, with their contents.
fn citing_files(root: &Path) -> Result<Vec<(String, String)>, Error> {
    let output = std::process::Command::new("git")
        .arg("ls-files")
        .arg("-z")
        .arg("--")
        .args(CITING_ROOTS)
        .current_dir(root)
        .output()?;
    if !output.status.success() {
        return Err(format!(
            "git ls-files failed: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        )
        .into());
    }
    let mut files = Vec::new();
    for path in output
        .stdout
        .split(|byte| *byte == 0)
        .filter(|path| !path.is_empty())
    {
        let path = String::from_utf8_lossy(path).into_owned();
        let Ok(bytes) = std::fs::read(root.join(&path)) else {
            continue; // deleted in the working tree but not yet in the index
        };
        if let Ok(text) = String::from_utf8(bytes) {
            files.push((path, text));
        }
    }
    files.sort();
    Ok(files)
}

/// The ADR numbers one line cites, as `ADR-NNNN` or `adr/NNNN-`.
fn cited_on(line: &str) -> BTreeSet<u32> {
    let mut cited = BTreeSet::new();
    for (marker, needs_dash) in [("ADR-", false), ("adr/", true)] {
        let mut rest = line;
        while let Some(at) = rest.find(marker) {
            let after = &rest[at + marker.len()..];
            let digits = after
                .get(..4)
                .filter(|d| d.bytes().all(|b| b.is_ascii_digit()));
            let next = after.as_bytes().get(4).copied();
            let ends = if needs_dash {
                next == Some(b'-')
            } else {
                !next.is_some_and(|b| b.is_ascii_digit())
            };
            if let (Some(digits), true) = (digits, ends)
                && let Ok(number) = digits.parse()
            {
                cited.insert(number);
            }
            rest = after;
        }
    }
    cited
}

/// ADR number → citing file → how many of its lines cite it.
type Citations = BTreeMap<u32, BTreeMap<String, usize>>;

/// Every citation in `files`, counted by line.
fn citations(files: &[(String, String)]) -> Citations {
    let mut citations = Citations::new();
    for (path, text) in files {
        for line in text.lines() {
            for number in cited_on(line) {
                *citations
                    .entry(number)
                    .or_default()
                    .entry(path.clone())
                    .or_default() += 1;
            }
        }
    }
    citations
}

/// `` `path` (n), … ``.
fn file_list(by_file: &BTreeMap<String, usize>) -> String {
    by_file
        .iter()
        .map(|(path, n)| format!("`{path}` ({n})"))
        .collect::<Vec<_>>()
        .join(", ")
}

/// One finding per file that cites an ADR that does not exist.
fn dangling_findings(
    adrs: &BTreeMap<u32, (String, String)>,
    citations: &Citations,
) -> Vec<Finding> {
    let mut findings = Vec::new();
    for (number, by_file) in citations
        .iter()
        .filter(|(number, _)| !adrs.contains_key(number))
    {
        for path in by_file.keys() {
            findings.push(
                Finding::new(
                    path,
                    "gen-docs",
                    format!("cites ADR {number:04}, which is not under docs/adr/"),
                )
                .with_hint("cite the ADR that exists, or merge the ADR first"),
            );
        }
    }
    findings
}

/// Renders `adr-index.md`: the uncited ADRs and the dangling citations.
#[must_use]
pub fn adr_index(adrs: &BTreeMap<u32, (String, String)>, citations: &Citations) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "# ADR index\n\n{GENERATED}\n");
    let _ = writeln!(
        out,
        "A citation is `ADR-NNNN`, or a link to `adr/NNNN-…`, in a tracked file under `{}`. \
         `cargo xtask gen-docs --adr-citations [ADR-NNNN]` prints which files cite each ADR.\n",
        CITING_ROOTS.join("`, `")
    );
    let _ = writeln!(out, "## Cited nowhere\n");
    let uncited: Vec<_> = adrs
        .iter()
        .filter(|(number, _)| !citations.contains_key(number))
        .collect();
    if uncited.is_empty() {
        let _ = writeln!(out, "None.");
    }
    for (number, (file, title)) in uncited {
        let _ = writeln!(out, "- [ADR-{number:04}](../adr/{file}) {title}");
    }
    let _ = writeln!(
        out,
        "\n## Citations of ADRs that do not exist\n\nThis list must be empty: \
         `cargo xtask gen-docs --check` fails while it is not.\n"
    );
    let dangling: Vec<_> = citations
        .iter()
        .filter(|(number, _)| !adrs.contains_key(number))
        .collect();
    if dangling.is_empty() {
        let _ = writeln!(out, "None.");
    }
    for (number, by_file) in dangling {
        let _ = writeln!(out, "- ADR-{number:04}: {}", file_list(by_file));
    }
    out
}

/// Renders the citation map for every ADR, or for `only`. Printed, never committed.
#[must_use]
pub fn citation_map(
    adrs: &BTreeMap<u32, (String, String)>,
    citations: &Citations,
    only: Option<u32>,
) -> String {
    let mut out =
        String::from("| ADR | Title | Files | Lines | Cited in |\n|---|---|---|---|---|\n");
    let numbers: BTreeSet<u32> = adrs.keys().chain(citations.keys()).copied().collect();
    for number in numbers
        .into_iter()
        .filter(|n| only.is_none_or(|only| only == *n))
    {
        let title = adrs
            .get(&number)
            .map_or("(no such ADR)", |(_, title)| title.as_str());
        let empty = BTreeMap::new();
        let by_file = citations.get(&number).unwrap_or(&empty);
        let lines: usize = by_file.values().sum();
        let _ = writeln!(
            out,
            "| {number:04} | {} | {} | {lines} | {} |",
            cell(title),
            by_file.len(),
            file_list(by_file)
        );
    }
    out
}

#[cfg(test)]
mod tests {
    use std::collections::{BTreeMap, BTreeSet};

    use super::{adr_index, citation_map, citations, cited_on, crate_graph, dangling_findings};
    use crate::checks::crates::Crate;

    /// `ADR-` followed by `n`, built at run time so this file cites nothing it does not mean to.
    fn adr(n: u32) -> String {
        format!("ADR{}{n:04}", '-')
    }

    #[test]
    fn a_line_cites_by_label_or_by_link_once_each() {
        let line = format!(
            "see [{}](../adr/0013-async.md) and {}'s rule",
            adr(13),
            adr(170)
        );
        assert_eq!(cited_on(&line), BTreeSet::from([13, 170]));
        // Five digits, or a path without the dash, is not a citation.
        assert_eq!(
            cited_on(&format!("{}5 adr/0013.md", adr(1234))),
            BTreeSet::new()
        );
    }

    #[test]
    fn the_index_lists_the_uncited_and_the_dangling_and_the_map_counts_lines() {
        let adrs = BTreeMap::from([
            (1, ("0001-one.md".to_owned(), "One".to_owned())),
            (2, ("0002-two.md".to_owned(), "Two".to_owned())),
        ]);
        let files = vec![
            (
                "crates/a.rs".to_owned(),
                format!("{}\n{} and {}\n", adr(1), adr(1), adr(9)),
            ),
            ("ui/b.ts".to_owned(), format!("{}\n", adr(1))),
        ];
        let cited = citations(&files);
        let index = adr_index(&adrs, &cited);
        assert!(
            index.contains("- [ADR-0002](../adr/0002-two.md) Two"),
            "{index}"
        );
        assert!(
            !index.contains("ADR-0001]"),
            "a cited ADR is not listed: {index}"
        );
        assert!(
            index.contains(&format!("- {}: `crates/a.rs` (1)", adr(9))),
            "{index}"
        );
        assert_eq!(
            index,
            adr_index(&adrs, &cited),
            "the same input renders the same bytes"
        );

        let found = dangling_findings(&adrs, &cited);
        assert_eq!(found.len(), 1, "{found:?}");
        assert_eq!(found[0].file, "crates/a.rs");

        let map = citation_map(&adrs, &cited, None);
        assert!(
            map.contains("| 0001 | One | 2 | 3 | `crates/a.rs` (2), `ui/b.ts` (1) |"),
            "{map}"
        );
        assert!(map.contains("| 0002 | Two | 0 | 0 |  |"), "{map}");
        assert!(
            map.contains("| 0009 | (no such ADR) | 1 | 1 | `crates/a.rs` (1) |"),
            "{map}"
        );
        let one = citation_map(&adrs, &cited, Some(2));
        assert_eq!(one.lines().count(), 3, "header, rule and one row: {one}");
    }

    #[test]
    fn the_graph_groups_by_layer_and_draws_only_non_test_edges() {
        let krate = |name: &str, layer: &str, normal: &[&str], dev: &[&str]| Crate {
            name: name.into(),
            dir: format!("crates/{name}"),
            normal: normal.iter().map(|n| (*n).to_owned()).collect(),
            dev: dev.iter().map(|n| (*n).to_owned()).collect(),
            card: Some(serde_json::json!({"layer": layer, "purpose": "Does a | b."})),
            readme: None,
            lib: true,
        };
        let crates = vec![
            krate("pos-core", "core", &[], &[]),
            krate("pos-edge", "app", &["pos-core"], &["fakes"]),
            krate("fakes", "testing", &[], &[]),
        ];
        let graph = crate_graph(&crates);
        assert!(
            graph.contains("  subgraph core\n    pos_core[\"pos-core\"]\n  end"),
            "{graph}"
        );
        assert!(graph.contains("  pos_edge --> pos_core\n"), "{graph}");
        assert!(!graph.contains("pos_edge --> fakes"), "{graph}");
        assert!(
            graph.contains(
                "| `fakes` | testing | `crates/fakes` | Does a \\| b. | — | `pos-edge` |"
            ),
            "{graph}"
        );
        assert!(
            graph.find("subgraph core") < graph.find("subgraph app"),
            "layers in ADR-0170 order"
        );
    }
}
