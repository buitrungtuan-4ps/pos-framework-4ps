//! `codeowners-crates.txt`: the line the root `CODEOWNERS` would hold for each workspace crate, from
//! its contract card's owners, so the card is the one source of who owns a crate
//! ([ADR-0170](../../../docs/adr/0170-repository-layout-code-naming-and-size-rules.md) decision 5).
//!
//! The check is one way and never writes `CODEOWNERS`. A `CODEOWNERS` line whose pattern is exactly
//! a crate's directory must name that crate's card owners, in order, or `gen-docs --check` fails on
//! that line and prints the line the card asks for. A crate with no line of its own is not a
//! failure: it is routed by no team yet, and adding a line is a change to `CODEOWNERS`, which a
//! person makes. Nothing here routes `CODEOWNERS` itself.

use std::fmt::Write as _;

use crate::Finding;
use crate::checks::crates::Crate;

/// The comment block the file opens with.
const HEADER: &str = "\
# Generated by `cargo xtask gen-docs` from each crate's [package.metadata.pos] owners. Do not edit:
# run it and commit the result.
#
# The line CODEOWNERS would hold for each workspace crate, so the card is the one source of who
# owns a crate. `cargo xtask gen-docs --check` fails where a crate's own line in the root
# CODEOWNERS differs from its line here. A crate with no line there is routed by no team yet;
# adding one is a change to CODEOWNERS, which a person makes.
";

/// Each crate with owners on its card, as `(pattern, owners)`, in directory order (`pos-cloud`
/// before `pos-cloud-api`), as the crate graph lists them.
fn lines(crates: &[Crate]) -> Vec<(String, Vec<String>)> {
    let mut lines: Vec<(&str, Vec<String>)> = crates
        .iter()
        .filter_map(|krate| {
            let owners: Vec<String> = krate
                .card
                .as_ref()?
                .get("owners")?
                .as_array()?
                .iter()
                .filter_map(|owner| owner.as_str().map(str::to_owned))
                .collect();
            (!owners.is_empty()).then_some((krate.dir.as_str(), owners))
        })
        .collect();
    lines.sort();
    lines
        .into_iter()
        .map(|(dir, owners)| (format!("/{dir}/"), owners))
        .collect()
}

/// Renders `codeowners-crates.txt`.
#[must_use]
pub fn render(crates: &[Crate]) -> String {
    let lines = lines(crates);
    let width = lines
        .iter()
        .map(|(pattern, _)| pattern.len())
        .max()
        .unwrap_or(0);
    let mut out = format!("{HEADER}\n");
    for (pattern, owners) in &lines {
        let _ = writeln!(out, "{pattern:width$} {}", owners.join(" "));
    }
    out
}

/// A finding for each `CODEOWNERS` line whose pattern is a crate's directory and whose owners are
/// not that crate's card owners.
#[must_use]
pub fn mismatches(crates: &[Crate], codeowners: &str) -> Vec<Finding> {
    let wanted = lines(crates);
    let mut findings = Vec::new();
    for (number, line) in codeowners.lines().enumerate() {
        let mut fields = line.split_whitespace();
        let Some(pattern) = fields.next().filter(|field| !field.starts_with('#')) else {
            continue;
        };
        let Some((_, owners)) = wanted.iter().find(|(want, _)| want == pattern) else {
            continue;
        };
        let routed: Vec<&str> = fields.collect();
        if routed.iter().copied().ne(owners.iter().map(String::as_str)) {
            findings.push(
                Finding::new(
                    "CODEOWNERS",
                    "gen-docs",
                    format!(
                        "`{pattern}` routes to {routed:?}, but the crate's card names {owners:?}"
                    ),
                )
                .at_line(u32::try_from(number + 1).unwrap_or(u32::MAX))
                .with_hint(format!(
                    "change the card, or have a person set this line to `{pattern} {}`",
                    owners.join(" ")
                )),
            );
        }
    }
    findings
}

#[cfg(test)]
mod tests {
    use super::{mismatches, render};
    use crate::checks::crates::Crate;

    fn krate(dir: &str, owners: &[&str]) -> Crate {
        Crate {
            name: dir.rsplit('/').next().unwrap_or(dir).to_owned(),
            dir: dir.to_owned(),
            card: Some(serde_json::json!({ "owners": owners })),
            ..Crate::default()
        }
    }

    fn crates() -> Vec<Crate> {
        vec![
            krate("crates/b", &["@team-b"]),
            krate("crates/a", &["@team-a", "@team-x"]),
            Crate {
                name: "nocard".into(),
                dir: "crates/nocard".into(),
                ..Crate::default()
            },
        ]
    }

    #[test]
    fn one_line_per_carded_crate_sorted_and_aligned() {
        let text = render(&crates());
        let body: Vec<&str> = text.lines().filter(|line| !line.starts_with('#')).collect();
        assert_eq!(
            body,
            ["", "/crates/a/ @team-a @team-x", "/crates/b/ @team-b"]
        );
    }

    #[test]
    fn a_crate_line_naming_other_owners_fails_on_that_line() {
        let codeowners = "# routing\n/crates/a/ @team-a @team-x\n/crates/b/   @team-z\n";
        let found = mismatches(&crates(), codeowners);
        assert_eq!(found.len(), 1);
        let finding = found.first().expect("one finding");
        assert_eq!(finding.line, Some(3));
        assert!(
            finding
                .fix_hint
                .as_deref()
                .unwrap_or_default()
                .contains("/crates/b/ @team-b")
        );
    }

    #[test]
    fn owners_in_another_order_differ() {
        let found = mismatches(&crates(), "/crates/a/ @team-x @team-a\n");
        assert_eq!(found.len(), 1);
    }

    #[test]
    fn a_crate_with_no_line_and_a_line_for_no_crate_are_not_failures() {
        assert!(mismatches(&crates(), "/docs/ @team-z\n/crates/ @team-z\n* @team-z\n").is_empty());
    }

    #[test]
    fn the_committed_file_is_what_the_cards_render() {
        let crates = crate::checks::crates::load(&crate::checks::repo_root()).expect("metadata");
        assert_eq!(
            render(&crates),
            include_str!("../../../docs/generated/codeowners-crates.txt")
        );
    }

    #[test]
    fn the_root_codeowners_agrees_with_the_cards() {
        let crates = crate::checks::crates::load(&crate::checks::repo_root()).expect("metadata");
        let found = mismatches(&crates, include_str!("../../../CODEOWNERS"));
        assert!(found.is_empty(), "{found:?}");
    }
}
