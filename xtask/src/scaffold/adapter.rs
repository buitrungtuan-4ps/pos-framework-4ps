//! `cargo xtask new adapter --kind <kind>`: a sandbox adapter for a port, built on
//! `cargo xtask new crate`, that passes the port's shared contract suite from its first build
//! ([ADR-0176](../../../docs/adr/0176-the-adapter-and-country-standard.md)).
//!
//! Every kind has the same three parts: a transport seam (the only thing that touches the device or
//! the service), a pure core implementing the port over it, and `tests/contract.rs`, which drives the
//! port's suite from `pos-contract-tests` against an in-memory transport.
//!
//! **No vendor.** The crate is `<kind>-sandbox` and the command takes no name: an adapter for a real
//! vendor is written from the sandbox once the owner has chosen the vendor. Printers and storage are
//! not catalogue families ([ADR-0153](../../../docs/adr/0153-a-vendor-is-a-provider-the-cloud-chooses.md)),
//! so these kinds export no provider descriptor.
//!
//! The generated crate depends on `pos-ports`, whose README's Used by line `xtask crates` then
//! expects to name it. The generator does not edit another crate's files, `pos-ports` and
//! `pos-proto` least of all, so it says which lines to add; `xtask crates` prints each one.

use std::path::Path;

use super::Plan;
use super::krate::{Parts, Spec, plan_with};
use crate::checks::Error;
use crate::checks::crates::adr_numbers;

/// ADR-0026 (port shapes) and ADR-0176 (this standard), which every generated adapter cites.
const ADRS: [u32; 2] = [26, 176];

/// The kinds this generator writes, by `--kind`.
const KINDS: &str = "printer, storage";

/// One kind of adapter: the port it implements and the files that differ from kind to kind.
struct Kind {
    /// The `--kind` value, and the first half of the crate name.
    name: &'static str,
    /// The card's purpose.
    purpose: &'static str,
    /// The workspace crates it depends on outside tests.
    dependencies: &'static [&'static str],
    /// The README's Owns section.
    owns: &'static str,
    /// The `src/lib.rs` template.
    lib: &'static str,
    /// The `tests/contract.rs` template.
    contract: &'static str,
}

const PRINTER: Kind = Kind {
    name: "printer",
    purpose: "A sandbox `PrinterDriver` over a transport seam, generated by `cargo xtask new \
              adapter`: the starting point for a printer adapter.",
    dependencies: &["pos-ports", "pos-proto"],
    owns: "- `SandboxPrinter`, the `PrinterDriver` over the `Transport` seam\n\
           - `encode`, the sandbox's command language, which a real adapter replaces",
    lib: include_str!("../../templates/adapter/printer/lib.rs.tmpl"),
    contract: include_str!("../../templates/adapter/printer/contract.rs.tmpl"),
};

const STORAGE: Kind = Kind {
    name: "storage",
    purpose: "A sandbox `BlobStore` over a transport seam, generated by `cargo xtask new adapter`: the \
              starting point for a storage adapter.",
    dependencies: &["pos-ports"],
    owns: "- `SandboxStorage`, the `BlobStore` over the `Transport` seam, with the listing that \
           keeps to its prefix",
    lib: include_str!("../../templates/adapter/storage/lib.rs.tmpl"),
    contract: include_str!("../../templates/adapter/storage/contract.rs.tmpl"),
};

/// The workspace crates every generated adapter's contract test uses.
const TEST_DEPENDENCIES: [&str; 2] = ["pos-contract-tests", "pos-fakes"];

/// Reads `--kind <kind>`, then plans against the repository at `root`.
///
/// # Errors
///
/// [`Error`] for a missing or unknown kind or argument, or anything [`plan`] refuses.
pub fn plan_from_args(root: &Path, args: &[&String]) -> Result<Plan, Error> {
    let kind = match args {
        [flag, kind] if flag.as_str() == "--kind" => kind.as_str(),
        _ => return Err(format!("usage: cargo xtask new adapter --kind <{KINDS}>").into()),
    };
    let codeowners = std::fs::read_to_string(root.join("CODEOWNERS"))?;
    let adrs = adr_numbers(&root.join("docs/adr"))?;
    plan(kind, &codeowners, &adrs)
}

/// The sandbox adapter of `kind`.
///
/// # Errors
///
/// [`Error`] for an unknown kind, or anything [`plan_with`] refuses.
pub fn plan(
    kind: &str,
    codeowners: &str,
    adrs: &std::collections::BTreeSet<u32>,
) -> Result<Plan, Error> {
    let kind = match kind {
        "printer" => &PRINTER,
        "storage" => &STORAGE,
        other => return Err(format!("no adapter kind `{other}`; the kinds are {KINDS}").into()),
    };
    let name = format!("{}-sandbox", kind.name);
    let spec = Spec {
        name: name.clone(),
        layer: "adapter".into(),
        purpose: kind.purpose.into(),
        adrs: ADRS.to_vec(),
    };
    plan_with(&spec, codeowners, adrs, &parts(kind, &name))
}

/// What `kind` adds to the plain crate.
fn parts(kind: &Kind, name: &str) -> Parts {
    let path = |dependency: &str| format!("{dependency} = {{ path = \"../../{dependency}\" }}\n");
    let quoted = |names: &[&str]| {
        names
            .iter()
            .map(|n| format!("`{n}`"))
            .collect::<Vec<_>>()
            .join(", ")
    };
    let mut dependencies: String = kind.dependencies.iter().map(|d| path(d)).collect();
    dependencies.push_str("\n[dev-dependencies]\n");
    dependencies.extend(TEST_DEPENDENCIES.iter().map(|d| path(d)));
    let neighbours = quoted(&[kind.dependencies, &TEST_DEPENDENCIES].concat());
    Parts {
        dependencies,
        depends: format!(
            "{}; in tests, {}",
            quoted(kind.dependencies),
            quoted(&TEST_DEPENDENCIES)
        ),
        owns: kind.owns.into(),
        entry_points: "- [`src/lib.rs`](src/lib.rs)\n\
                       - [`tests/contract.rs`](tests/contract.rs): the port's shared contract suite"
            .into(),
        lib: kind.lib,
        extra: vec![("tests/contract.rs", kind.contract)],
        values: vec![("crate_ident", name.replace('-', "_"))],
        next: vec![
            format!("`cargo test -p {name}` runs the port's contract suite against the sandbox"),
            format!(
                "`cargo xtask crates` prints the Used by line the README of each of {neighbours} \
                 needs to name `{name}`; `pos-ports` and `pos-proto` are owner-reviewed, so the \
                 generator leaves their files to you"
            ),
        ],
    }
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeSet;

    use super::plan;

    const CODEOWNERS: &str = include_str!("../../../CODEOWNERS");

    fn adrs() -> BTreeSet<u32> {
        [26, 176].into_iter().collect()
    }

    /// The files `kind` writes, as (path, contents) pairs.
    fn files(kind: &str) -> Vec<(String, String)> {
        plan(kind, CODEOWNERS, &adrs()).expect("planned").files
    }

    fn golden(files: &[(&str, &str)]) -> Vec<(String, String)> {
        files
            .iter()
            .map(|(path, text)| ((*path).to_owned(), (*text).to_owned()))
            .collect()
    }

    #[test]
    fn the_printer_it_writes_is_the_golden_one() {
        let expected = golden(&[
            (
                "crates/adapters/printer-sandbox/Cargo.toml",
                include_str!("../../tests/golden/new-adapter/printer/Cargo.toml.golden"),
            ),
            (
                "crates/adapters/printer-sandbox/README.md",
                include_str!("../../tests/golden/new-adapter/printer/README.md.golden"),
            ),
            (
                "crates/adapters/printer-sandbox/src/lib.rs",
                include_str!("../../tests/golden/new-adapter/printer/lib.rs.golden"),
            ),
            (
                "crates/adapters/printer-sandbox/tests/contract.rs",
                include_str!("../../tests/golden/new-adapter/printer/contract.rs.golden"),
            ),
        ]);
        assert_eq!(files("printer"), expected);
    }

    #[test]
    fn the_storage_it_writes_is_the_golden_one() {
        let expected = golden(&[
            (
                "crates/adapters/storage-sandbox/Cargo.toml",
                include_str!("../../tests/golden/new-adapter/storage/Cargo.toml.golden"),
            ),
            (
                "crates/adapters/storage-sandbox/README.md",
                include_str!("../../tests/golden/new-adapter/storage/README.md.golden"),
            ),
            (
                "crates/adapters/storage-sandbox/src/lib.rs",
                include_str!("../../tests/golden/new-adapter/storage/lib.rs.golden"),
            ),
            (
                "crates/adapters/storage-sandbox/tests/contract.rs",
                include_str!("../../tests/golden/new-adapter/storage/contract.rs.golden"),
            ),
        ]);
        assert_eq!(files("storage"), expected);
    }

    #[test]
    fn a_kind_it_does_not_have_is_refused() {
        for kind in ["card", "fiscal", "qr", "printer-escpos", ""] {
            assert!(plan(kind, CODEOWNERS, &adrs()).is_err(), "{kind}");
        }
    }

    #[test]
    fn it_names_no_vendor_and_each_member_is_a_sandbox() {
        for kind in ["printer", "storage"] {
            let planned = plan(kind, CODEOWNERS, &adrs()).expect("planned");
            assert_eq!(planned.member, format!("crates/adapters/{kind}-sandbox"));
            assert_eq!(planned.package, format!("{kind}-sandbox"));
        }
    }

    #[test]
    fn it_says_which_neighbour_readmes_name_it_and_writes_none_of_them() {
        let planned = plan("printer", CODEOWNERS, &adrs()).expect("planned");
        assert!(
            planned
                .files
                .iter()
                .all(|(path, _)| path.starts_with("crates/adapters/printer-sandbox/"))
        );
        let said = planned.next.join("\n");
        for neighbour in ["pos-ports", "pos-proto", "pos-contract-tests", "pos-fakes"] {
            assert!(said.contains(&format!("`{neighbour}`")), "{neighbour}");
        }
    }
}
