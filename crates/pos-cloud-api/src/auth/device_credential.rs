//! A device credential: what activation mints for a box, and what [`super::bearer`] accepts as a
//! `posdev_<id>_<secret>` token ([ADR-0118](../../../../docs/adr/0118-one-credential-per-box-and-the-cloud-learns.md)).
//! Moved here from `pos-cloud`'s `activation` module, which re-exports it, so the minting and the
//! check live in one crate.

use core::fmt;

use sha2::{Digest, Sha256};

use pos_proto::ulid::Ulid;

use crate::auth::apikey::DEVICE_TOKEN_PREFIX;

/// `SHA-256` of a credential secret's bytes — what is stored and later compared, never the secret.
fn hash_secret(secret: &str) -> [u8; 32] {
    Sha256::digest(secret.as_bytes()).into()
}

/// A device credential's stored form: its public id and the hash of its secret.
///
/// The slot (tenant/store/device) it belongs to is the redeemed code's, filled in atomically by the
/// store, so it is not carried here. [`fmt::Debug`] redacts the hash, so nothing credential-shaped
/// reaches a log.
#[derive(Clone)]
pub struct DeviceCredential {
    /// The public id — the ULID half of the `posdev_<id>_<secret>` token.
    pub id: Ulid,
    secret_hash: [u8; 32],
}

impl DeviceCredential {
    /// The stored `SHA-256(secret)` — for the persistence adapter to write. The secret is
    /// unrecoverable after issuance.
    #[must_use]
    pub const fn secret_hash(&self) -> [u8; 32] {
        self.secret_hash
    }
}

impl fmt::Debug for DeviceCredential {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("DeviceCredential")
            .field("id", &self.id)
            .field("secret_hash", &"<redacted>")
            .finish()
    }
}

/// Mints a device credential: the record to store and the one-time token to return.
///
/// `id` and `secret` are generated by the caller from a CSPRNG. The returned token
/// (`posdev_<id>_<secret>`) is the only time the secret is visible; only its hash is kept.
#[must_use]
pub fn mint_device_credential(id: Ulid, secret: &str) -> (DeviceCredential, String) {
    let token = format!("{DEVICE_TOKEN_PREFIX}{id}_{secret}");
    let credential = DeviceCredential {
        id,
        secret_hash: hash_secret(secret),
    };
    (credential, token)
}

#[cfg(test)]
mod tests {
    use super::{hash_secret, mint_device_credential};

    use pos_proto::ulid::Ulid;

    #[test]
    fn the_credential_token_carries_the_id_but_the_record_hides_the_secret() {
        let id = Ulid::from_u128(0xDEAD_BEEF);
        let (credential, token) = mint_device_credential(id, "a-high-entropy-secret");
        assert!(token.starts_with("posdev_"));
        assert!(
            token.contains(&id.to_string()),
            "the token carries its public id"
        );
        assert!(
            token.contains("a-high-entropy-secret"),
            "the token shows the secret once"
        );
        // The stored record hashes the secret and never renders it.
        assert_eq!(
            credential.secret_hash(),
            hash_secret("a-high-entropy-secret")
        );
        let debugged = format!("{credential:?}");
        assert!(
            !debugged.contains("a-high-entropy-secret"),
            "got {debugged}"
        );
    }
}
